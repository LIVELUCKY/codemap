//! The grammar tier: tree-sitter parse plus a tags-style query per language.
//!
//! Capture convention of the query files under `languages/<lang>/tags.scm`:
//! `@definition.<kind>` with `@name` makes a definition of that kind; `@reference.<kind>` with `@name`
//! makes a reference; `@supertype` captures (repeatable) fill the supertypes; `@modifier` captures fill
//! the flags with the node text; `@annotation` captures fill the flags with `@<Name>`; `@path` (the
//! module of an import) goes into the flags as is. A node captured as `@literal` becomes a literal
//! symbol named by its text (a markdown link target, a JSON string value that looks like a path).
//!
//! A definition or reference is reported on the line of its `@name` capture, not of the node that
//! starts it: an annotated class is listed where `class X` stands, not where `@Resource` stands. A
//! definition ends where the node captured as `@definition.<kind>` ends.
//!
//! A definition may be matched by several patterns: its header gives the kind, and patterns captured as
//! `@definition.any` add modifiers, annotations and supertypes. Matches with the same role, name and line
//! are merged into one symbol; a symbol that only ever had the `any` kind is dropped. When two header
//! patterns match the same node (`const X = struct {}` is both a constant and a struct), the match with
//! more captures wins the kind, so a pattern can claim precedence by capturing its discriminating child.
//!
//! Supertype and annotation captures may cover a whole node (`BaseRepository()`, `@Resource("/x")`); the
//! text is reduced to the simple name.
//!
//! Upstream tags queries may carry property predicates such as `(#is-not? local)`, which need a locals
//! analysis this cursor does not run; patterns with any property predicate are skipped rather than
//! matched unconditionally. A node captured as `@ignore` (upstream marks keywords that look like calls,
//! `def` in Elixir) is dropped from the references, as tree-sitter-tags does.
//!
//! Some grammars parse an annotation with arguments at statement level as its own expression instead of
//! a modifier of the declaration that follows. A pattern captured as `@orphan` with `@orphan.annotation`
//! children marks such a statement; its annotations are adopted by the definition that starts on the
//! line right after it.

use std::collections::HashMap;
use std::sync::{Arc, Mutex, OnceLock};

use tree_sitter::{Language as TsLanguage, Parser, Query, QueryCursor, StreamingIterator};

use super::Language;
use crate::model::{Role, Symbol};

pub struct Grammar {
    pub language: TsLanguage,
    pub query: &'static str,
}

// `grammar_for`, generated by build.rs from languages/registry.toml.
include!(concat!(env!("OUT_DIR"), "/languages_grammars.rs"));

/// Compiled queries, one per language and query text; compiling costs far more than a parse of a
/// small file. The language is part of the key: TypeScript and TSX share one query text, and a query
/// compiled for one grammar reads the other's tree wrongly.
fn compiled(grammar: &Grammar) -> Arc<Query> {
    type Compiled = HashMap<(TsLanguage, usize), Arc<Query>>;
    static CACHE: OnceLock<Mutex<Compiled>> = OnceLock::new();
    let cache = CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    let key = (grammar.language.clone(), grammar.query.as_ptr() as usize);
    if let Some(query) = cache.lock().unwrap().get(&key) {
        return query.clone();
    }
    let query = Arc::new(
        Query::new(&grammar.language, grammar.query)
            .unwrap_or_else(|e| panic!("tags query does not compile: {e}")),
    );
    cache.lock().unwrap().insert(key, query.clone());
    query
}

pub fn parse(grammar: &Grammar, source: &[u8]) -> Vec<Symbol> {
    parse_checked(grammar, source).0
}

/// `parse` plus whether the syntax tree contains errors, in which case the grammar may have lost
/// everything after the broken spot and the caller should add what a generic scan still finds.
pub fn parse_checked(grammar: &Grammar, source: &[u8]) -> (Vec<Symbol>, bool) {
    let mut parser = Parser::new();
    if parser.set_language(&grammar.language).is_err() {
        return (Vec::new(), false);
    }
    let Some(tree) = parser.parse(source, None) else {
        return (Vec::new(), false);
    };
    let had_error = tree.root_node().has_error();
    let query = compiled(grammar);
    let names = query.capture_names();
    let skipped: Vec<bool> = (0..query.pattern_count())
        .map(|i| !query.property_predicates(i).is_empty())
        .collect();
    let mut cursor = QueryCursor::new();
    let mut matches = cursor.matches(&query, tree.root_node(), source);
    let mut merged: HashMap<(Role, String, u32), Symbol> = HashMap::new();
    let mut specificity: HashMap<(Role, String, u32), usize> = HashMap::new();
    let mut order: Vec<(Role, String, u32)> = Vec::new();
    // (last line of an orphan annotation statement, its annotation flags)
    // (first line, last line, flags) of annotations the grammar left outside their declaration.
    let mut orphans: Vec<(u32, u32, Vec<String>)> = Vec::new();
    // start bytes of nodes captured as @ignore, and the start byte of every reference's name node
    let mut ignored: std::collections::HashSet<usize> = std::collections::HashSet::new();
    let mut reference_starts: Vec<((Role, String, u32), usize)> = Vec::new();
    while let Some(m) = matches.next() {
        if skipped[m.pattern_index] {
            continue;
        }
        let mut role_kind: Option<(Role, String)> = None;
        let mut name: Option<String> = None;
        let mut line = 0u32;
        let mut flags = Vec::new();
        let mut supertypes = Vec::new();
        let mut orphan_end: Option<u32> = None;
        let mut orphan_flags = Vec::new();
        let mut drop = false;
        let mut name_start = 0usize;
        let mut name_line: Option<u32> = None;
        let mut start_line = u32::MAX;
        let mut end_line = 0u32;
        let mut orphan_start = 0u32;
        for capture in m.captures() {
            let capture_name = names[capture.index as usize];
            let text = || capture.node.utf8_text(source).unwrap_or("").to_string();
            if capture_name == "ignore" {
                ignored.insert(capture.node.start_byte());
                continue;
            }
            if capture_name == "orphan" {
                orphan_start = capture.node.start_position().row as u32 + 1;
                orphan_end = Some(capture.node.end_position().row as u32 + 1);
                continue;
            }
            if capture_name == "orphan.annotation" {
                orphan_flags.push(format!("@{}", simple_name(text().trim_start_matches('@'))));
                continue;
            }
            if capture_name == "literal" {
                let value = text().trim_matches(['"', '\'', '<', '>']).to_string();
                if !looks_like_link(&value) {
                    drop = true;
                    break;
                }
                role_kind = Some((Role::Literal, "literal".to_string()));
                name = Some(value);
                line = capture.node.start_position().row as u32 + 1;
            } else if let Some(kind) = capture_name.strip_prefix("definition.") {
                role_kind = Some((Role::Definition, kind.to_string()));
                line = capture.node.start_position().row as u32 + 1;
                start_line = line;
                end_line = capture.node.end_position().row as u32 + 1;
            } else if let Some(kind) = capture_name.strip_prefix("reference.") {
                role_kind = Some((Role::Reference, kind.to_string()));
                line = capture.node.start_position().row as u32 + 1;
            } else {
                match capture_name {
                    "name" => {
                        let text = text();
                        let text = text.trim_matches(['"', '\'']);
                        // A resource reference (`@drawable/ic_logo`, `@+id/logo`) is named by its
                        // last part, which is the name the resource is defined and used under.
                        let text = match text.strip_prefix('@') {
                            Some(resource) => resource.rsplit('/').next().unwrap_or(resource),
                            None => text,
                        };
                        name = Some(text.to_string());
                        name_start = capture.node.start_byte();
                        name_line = Some(capture.node.start_position().row as u32 + 1);
                    }
                    "supertype" => supertypes.push(simple_name(&text())),
                    "modifier" => flags.push(text()),
                    "annotation" => {
                        flags.push(format!("@{}", simple_name(text().trim_start_matches('@'))))
                    }
                    "path" => flags.push(text()),
                    _ => {}
                }
            }
        }
        if drop {
            continue;
        }
        if let Some(end) = orphan_end {
            orphans.push((orphan_start, end, orphan_flags));
            continue;
        }
        let (Some((role, kind)), Some(name)) = (role_kind, name) else {
            continue;
        };
        let line = name_line.unwrap_or(line);
        let start_line = start_line.min(line);
        let end_line = end_line.max(line);
        let key = (role, name.clone(), line);
        if role == Role::Reference {
            reference_starts.push((key.clone(), name_start));
        }
        let captures = m.captures().len();
        let entry = merged.entry(key.clone()).or_insert_with(|| {
            order.push(key.clone());
            Symbol {
                name,
                role,
                kind: kind.clone(),
                line,
                start_line,
                end_line,
                flags: Vec::new(),
                supertypes: Vec::new(),
            }
        });
        let known = specificity.entry(key).or_insert(0);
        if kind != "any" && (entry.kind == "any" || captures > *known) {
            entry.kind = kind;
            entry.start_line = start_line;
            entry.end_line = end_line;
            *known = captures;
        }
        for f in flags {
            if !entry.flags.contains(&f) {
                entry.flags.push(f);
            }
        }
        for s in supertypes {
            if !entry.supertypes.contains(&s) {
                entry.supertypes.push(s);
            }
        }
    }
    for (key, start) in reference_starts {
        if ignored.contains(&start) {
            merged.remove(&key);
        }
    }
    // An annotation the grammar leaves outside the declaration it belongs to (Kotlin's) belongs to
    // the definition whose name, or whose first line, follows it: its flags and its lines. Bottom up,
    // so a stack of them chains.
    orphans.sort_by_key(|o| std::cmp::Reverse(o.1));
    for (start, end, flags) in orphans {
        for symbol in merged.values_mut().filter(|s| {
            s.role == Role::Definition && (s.line == end + 1 || s.start_line == end + 1)
        }) {
            symbol.start_line = symbol.start_line.min(start);
            for f in &flags {
                if !symbol.flags.contains(f) {
                    symbol.flags.push(f.clone());
                }
            }
        }
    }
    let symbols = order
        .into_iter()
        .filter_map(|key| merged.remove(&key))
        .filter(|s| s.kind != "any")
        .collect();
    (symbols, had_error)
}

/// A string worth indexing as a link: a path (`/api/v1/books`) or a URL (`https://...`), no whitespace.
pub fn looks_like_link(text: &str) -> bool {
    let path = text.starts_with('/') && text.len() > 1;
    let url = text.contains("://") && !text.starts_with("://");
    (path || url) && !text.chars().any(char::is_whitespace)
}

/// `kotlin.Comparable<Book>()` becomes `Comparable`: the text up to the first `(` or `<`, last segment.
fn simple_name(text: &str) -> String {
    let head = text.split(['(', '<', ' ', '\n']).next().unwrap_or("");
    head.rsplit('.').next().unwrap_or(head).trim().to_string()
}

